"use client";

import { motion } from "motion/react";
import type { SopTemplate } from "@/lib/templates";

/**
 * A miniature A4 page that mirrors the generated document: same title band,
 * numbered section headings, hint lines and blank lines to fill. Rendered in
 * HTML so it appears instantly next to the section list.
 */
export function DocPreview({ tpl, uniName, href }: { tpl: SopTemplate; uniName: string; href: string }) {
  return (
    <div className="flex flex-col items-center">
      <motion.a
        href={href}
        target="_blank"
        initial={{ opacity: 0, y: 10, rotate: 0.8 }}
        animate={{ opacity: 1, y: 0, rotate: 0.8 }}
        whileHover={{ rotate: 0, y: -3 }}
        transition={{ type: "spring", stiffness: 260, damping: 22 }}
        className="relative block aspect-[1/1.414] w-full max-w-[300px] overflow-hidden rounded-[3px] bg-white shadow-[0_1px_0_rgba(0,0,0,.06),0_16px_30px_-16px_rgba(22,21,20,.45)] ring-1 ring-ink/10"
        title="Open full document"
      >
        <div className="h-[5px] bg-[#3e63dd]" />
        <div className="h-full overflow-hidden px-[9%] pt-[7%] text-[#1c2024]">
          <p className="text-[11px] font-bold leading-tight text-[#1f2d5c]">{tpl.title}</p>
          <p className="mt-0.5 text-[6px] text-[#60646c]">{uniName} template</p>
          <div className="mt-2.5 space-y-2">
            {tpl.sections.map((s, i) => (
              <div key={s.key + i}>
                <p className="text-[7px] font-bold text-[#3e63dd]">{i + 1}. {s.title}</p>
                {s.hint && <p className="mt-0.5 text-[5.5px] text-[#80838d]">{s.hint}</p>}
                <div className="mt-1 space-y-[3px]">
                  <span className="block h-px w-full bg-[#d9d9e0]" />
                  <span className="block h-px w-[86%] bg-[#d9d9e0]" />
                </div>
              </div>
            ))}
          </div>
        </div>
        <span aria-hidden className="absolute inset-x-0 bottom-0 h-10 bg-gradient-to-t from-white via-white to-transparent" />
        <span className="absolute bottom-1.5 left-[9%] text-[4.5px] text-[#80838d]">{tpl.title}, page 1, generated by Movents</span>
      </motion.a>
      <a href={href} target="_blank" className="mt-3 text-xs font-semibold text-tomato-ink hover:underline">Open full PDF</a>
    </div>
  );
}
